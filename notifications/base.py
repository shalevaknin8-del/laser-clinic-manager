# הממשק המשותף לכל ספקי ההתראות.
#
# כל ספק, בין אם הוא מדפיס לטרמינל, שולח מייל או שולח SMS,
# חייב לממש את אותה מתודה אחת בדיוק. כך שאר המערכת יכולה
# לשלוח הודעות בלי לדעת מי הספק ואיך הוא עובד.
#
# להוספת ערוץ חדש בעתיד: יוצרים מחלקה שיורשת מכאן,
# מממשים send, ורושמים אותה ב-factory. אפס שינוי בקוד קיים.
# ============================================================

from abc import ABC, abstractmethod


class NotificationError(Exception):
    """חריגה שנזרקת כאשר שליחת ההודעה נכשלה."""


class NotificationProvider(ABC):
    """
    מחלקת בסיס מופשטת לספק התראות.

    המחלקה מסומנת כמופשטת כדי שלא יהיה אפשר ליצור ממנה
    מופע ישירות. רק מחלקות יורשות שמימשו את send יכולות לפעול.
    """

    # שם הערוץ, לצורך רישום ביומן
    channel_name = "base"

    @abstractmethod
    def send(self, recipient, subject, message):
        """
        שולח הודעה ליעד.

        recipient - כתובת היעד: מספר טלפון או כתובת מייל
        subject   - נושא ההודעה. ערוצים כמו SMS מתעלמים ממנו
        message   - גוף ההודעה

        מחזיר True אם השליחה הצליחה.
        זורק NotificationError אם היא נכשלה.
        """
        raise NotImplementedError

    def is_configured(self):
        """
        בודק האם לספק יש את כל ההגדרות הנדרשות לפעולה.
        מאפשר לגלות בעיית הגדרות בעליית המערכת ולא בזמן שליחה.
        """
        return True